use std::fs::{self, File};
use std::io::{self, Read};
use std::path::{Component, Path, PathBuf};
use std::sync::atomic::{AtomicBool, Ordering};

use crate::archive::Fail;
use crate::ops::{Progress, Report};

pub fn is_sfv(path: &Path) -> bool {
    path.extension().and_then(|ext| ext.to_str()).is_some_and(|ext| ext.eq_ignore_ascii_case("sfv"))
}

pub fn create(
    root: &Path,
    sources: &[PathBuf],
    dest: &Path,
    cancel: &AtomicBool,
    progress: &mut dyn FnMut(&Progress),
) -> Result<Report, Fail> {
    let mut files = Vec::new();
    for source in sources {
        collect(source, root, dest, &mut files)?;
    }
    if files.is_empty() {
        return Err(Fail::Message("Nothing selected".into()));
    }
    let total = files.len() as u64;
    let mut out = String::from("; Generated by Rust Commander\n");
    for (index, (path, rel)) in files.iter().enumerate() {
        if cancel.load(Ordering::Relaxed) {
            return Ok(Report { cancelled: true, files: index as u64 });
        }
        if rel.contains('\n') {
            return Err(Fail::Message(format!("name has a newline: {rel}")));
        }
        let crc = match hash_file(path, cancel) {
            Ok(crc) => crc,
            Err(Fail::Cancelled) => return Ok(Report { cancelled: true, files: index as u64 }),
            Err(err) => return Err(err),
        };
        out.push_str(&format!("{rel} {crc:08X}\n"));
        progress(&Progress { done: index as u64 + 1, total, current: path.clone(), note: String::new() });
    }
    crate::ops::write_atomic(dest, out.as_bytes())?;
    Ok(Report { cancelled: false, files: total })
}

pub fn verify(sfv: &Path, cancel: &AtomicBool, progress: &mut dyn FnMut(&Progress)) -> Result<Report, Fail> {
    let root = sfv.parent().unwrap_or(Path::new("."));
    let text = fs::read_to_string(sfv)?;
    let rows: Vec<_> = text.lines().filter_map(parse_line).collect();
    let total = rows.len() as u64;
    let mut ok = 0u64;
    let mut failed = 0u64;
    let mut missing = 0u64;
    let mut issues = Vec::new();
    for (index, (name, crc)) in rows.iter().enumerate() {
        if cancel.load(Ordering::Relaxed) {
            return Ok(Report { cancelled: true, files: ok });
        }
        let current = PathBuf::from(name);
        let done = index as u64;
        progress(&Progress { done, total, current: current.clone(), note: check_note(done, total, name, &issues) });
        match check_one(root, name, *crc, cancel) {
            Check::Cancelled => return Ok(Report { cancelled: true, files: ok }),
            Check::Ok => ok += 1,
            Check::Missing => {
                missing += 1;
                issues.push(format!("missing  {name}"));
            }
            Check::Mismatch => {
                failed += 1;
                issues.push(format!("CRC mismatch  {name}"));
            }
            Check::Outside => {
                failed += 1;
                issues.push(format!("symlink outside  {name}"));
            }
            Check::Bad => {
                failed += 1;
                issues.push(format!("bad path  {name}"));
            }
            Check::Error(err) => {
                failed += 1;
                issues.push(format!("{err}  {name}"));
            }
        }
        let done = done + 1;
        progress(&Progress { done, total, current, note: check_note(done, total, name, &issues) });
    }
    if issues.is_empty() {
        return Ok(Report { cancelled: false, files: ok });
    }
    let mut text = format!("OK {ok}, failed {failed}, missing {missing}");
    let shown = issues.len().min(ISSUE_LIMIT);
    text.push('\n');
    text.push_str(&issues[..shown].join("\n"));
    if issues.len() > ISSUE_LIMIT {
        text.push_str(&format!("\n… {} more", issues.len() - ISSUE_LIMIT));
    }
    Err(Fail::Message(text))
}

const ISSUE_LIMIT: usize = 400;

fn check_note(done: u64, total: u64, name: &str, issues: &[String]) -> String {
    let mut text = format!("Checking {done}/{total}\n{name}\n\n{}", issues.len());
    if issues.is_empty() {
        return text;
    }
    text.push('\n');
    let skip = issues.len().saturating_sub(8);
    if skip > 0 {
        text.push_str(&format!("… {skip} earlier\n"));
    }
    text.push_str(&issues[skip..].join("\n"));
    text
}

fn collect(path: &Path, root: &Path, dest: &Path, out: &mut Vec<(PathBuf, String)>) -> Result<(), Fail> {
    if path == dest {
        return Ok(());
    }
    let rel = path.strip_prefix(root).map_err(|_| Fail::Message("file is outside the folder".into()))?;
    let rel = slash(rel);
    if rel.is_empty() {
        return Err(Fail::Message("cannot checksum the folder itself".into()));
    }
    let meta = fs::symlink_metadata(path)?;
    if meta.file_type().is_symlink() {
        let resolved = path.canonicalize().unwrap_or_else(|_| path.to_path_buf());
        let root_real = root.canonicalize().unwrap_or_else(|_| root.to_path_buf());
        if !resolved.starts_with(&root_real) {
            return Err(Fail::Message(format!("symlink outside  {}", path.display())));
        }
    }
    if meta.is_dir() && !meta.file_type().is_symlink() {
        let mut children: Vec<_> = fs::read_dir(path)?.map(|entry| entry.map(|entry| entry.path())).collect::<io::Result<_>>()?;
        children.sort();
        for child in children {
            collect(&child, root, dest, out)?;
        }
        return Ok(());
    }
    if is_sfv(path) {
        return Ok(());
    }
    out.push((path.to_path_buf(), rel));
    Ok(())
}

fn check_one(root: &Path, name: &str, expect: u32, cancel: &AtomicBool) -> Check {
    let Some(rel) = safe_rel(name) else { return Check::Bad };
    let path = root.join(&rel);
    if let Err(kind) = stays_inside(root, &path) {
        return kind;
    }
    match hash_file(&path, cancel) {
        Ok(crc) if crc == expect => Check::Ok,
        Ok(_) => Check::Mismatch,
        Err(Fail::Cancelled) => Check::Cancelled,
        Err(Fail::Message(err)) if missing_file(&err) => Check::Missing,
        Err(err) => Check::Error(err.to_string()),
    }
}

fn missing_file(err: &str) -> bool {
    err.contains("No such file") || err.contains("not found") || err.contains("os error 2")
}

enum Check {
    Ok,
    Missing,
    Mismatch,
    Outside,
    Bad,
    Cancelled,
    Error(String),
}

fn stays_inside(root: &Path, path: &Path) -> Result<(), Check> {
    let mut cur = root.to_path_buf();
    if let Ok(rel) = path.strip_prefix(root) {
        for part in rel.components() {
            let Component::Normal(name) = part else { return Err(Check::Bad) };
            cur.push(name);
            if fs::symlink_metadata(&cur).is_ok_and(|meta| meta.file_type().is_symlink()) {
                let Ok(real) = cur.canonicalize() else { return Err(Check::Outside) };
                let Ok(root_real) = root.canonicalize() else { return Err(Check::Outside) };
                if !real.starts_with(&root_real) {
                    return Err(Check::Outside);
                }
            }
        }
    }
    Ok(())
}

fn hash_file(path: &Path, cancel: &AtomicBool) -> Result<u32, Fail> {
    let mut file = File::open(path)?;
    let mut hasher = crc32fast::Hasher::new();
    let mut buf = vec![0u8; 1024 * 1024];
    loop {
        // Stop between reads so cancel does not wait out a large file.
        if cancel.load(Ordering::Relaxed) {
            return Err(Fail::Cancelled);
        }
        let n = file.read(&mut buf)?;
        if n == 0 {
            break;
        }
        hasher.update(&buf[..n]);
    }
    Ok(hasher.finalize())
}

fn parse_line(line: &str) -> Option<(String, u32)> {
    let line = line.trim();
    if line.is_empty() || line.starts_with(';') {
        return None;
    }
    let (name, crc) = line.rsplit_once(char::is_whitespace)?;
    let name = name.trim();
    if name.is_empty() || crc.len() != 8 || !crc.chars().all(|c| c.is_ascii_hexdigit()) {
        return None;
    }
    Some((name.to_string(), u32::from_str_radix(crc, 16).ok()?))
}

fn slash(path: &Path) -> String {
    let mut out = String::new();
    for part in path.components() {
        if let Component::Normal(part) = part {
            if !out.is_empty() {
                out.push('/');
            }
            out.push_str(&part.to_string_lossy());
        }
    }
    out
}

fn safe_rel(name: &str) -> Option<PathBuf> {
    if name.is_empty() || name.contains('\0') {
        return None;
    }
    let path = Path::new(name);
    if path.is_absolute() {
        return None;
    }
    let mut out = PathBuf::new();
    for part in path.components() {
        match part {
            Component::Normal(part) => out.push(part),
            Component::CurDir => {}
            _ => return None,
        }
    }
    (!out.as_os_str().is_empty()).then_some(out)
}

#[cfg(test)]
mod tests {
    use super::*;
    use std::sync::atomic::AtomicU64;

    fn tmp(name: &str) -> PathBuf {
        static N: AtomicU64 = AtomicU64::new(0);
        let path = std::env::temp_dir().join(format!(
            "rust-commander-sfv-{}-{}-{name}",
            std::process::id(),
            N.fetch_add(1, Ordering::Relaxed)
        ));
        let _ = fs::remove_dir_all(&path);
        fs::create_dir_all(&path).unwrap();
        path
    }

    #[test]
    fn create_and_verify_match_mismatch_and_dotdot() {
        let dir = tmp("sfv");
        fs::write(dir.join("a.txt"), b"alpha").unwrap();
        let dest = dir.join("a.sfv");
        let cancel = AtomicBool::new(false);
        create(&dir, &[dir.join("a.txt")], &dest, &cancel, &mut |_| {}).unwrap();
        let text = fs::read_to_string(&dest).unwrap();
        assert!(text.starts_with("; Generated by Rust Commander\n"));
        assert!(verify(&dest, &cancel, &mut |_| {}).is_ok());
        let bad = text.replace(|c: char| c.is_ascii_hexdigit() && text.lines().nth(1).is_some_and(|line| line.contains(c)), "0");
        let _ = bad;
        let mut lines: Vec<_> = text.lines().map(str::to_string).collect();
        lines[1] = "a.txt 00000000".into();
        lines.push("../evil.txt 00000000".into());
        fs::write(&dest, lines.join("\n")).unwrap();
        let err = verify(&dest, &cancel, &mut |_| {}).unwrap_err().to_string();
        assert!(err.contains("CRC mismatch"), "{err}");
        assert!(err.contains("bad path"), "{err}");
        let _ = fs::remove_dir_all(&dir);
    }

    #[test]
    fn leaves_other_part_file_alone() {
        let dir = tmp("part");
        fs::write(dir.join("a.txt"), b"alpha").unwrap();
        fs::write(dir.join("a.sfv.part"), b"download").unwrap();
        create(&dir, &[dir.join("a.txt")], &dir.join("a.sfv"), &AtomicBool::new(false), &mut |_| {}).unwrap();
        assert_eq!(fs::read(dir.join("a.sfv.part")).unwrap(), b"download");
        let _ = fs::remove_dir_all(&dir);
    }

    #[test]
    fn verify_names_a_missing_file_and_stops_when_cancelled() {
        let dir = tmp("miss");
        fs::write(dir.join("a.txt"), b"alpha").unwrap();
        let dest = dir.join("a.sfv");
        let cancel = AtomicBool::new(false);
        create(&dir, &[dir.join("a.txt")], &dest, &cancel, &mut |_| {}).unwrap();
        fs::write(&dest, "gone.bin AAAAAAAA\n").unwrap();
        let err = verify(&dest, &cancel, &mut |_| {}).unwrap_err().to_string();
        assert!(err.contains("missing  gone.bin"), "{err}");
        fs::write(dir.join("a.txt"), b"alpha").unwrap();
        create(&dir, &[dir.join("a.txt")], &dest, &cancel, &mut |_| {}).unwrap();
        let report = verify(&dest, &cancel, &mut |_| {
            cancel.store(true, Ordering::Relaxed);
        })
        .unwrap();
        assert!(report.cancelled);
        let _ = fs::remove_dir_all(&dir);
    }
}
