use std::sync::atomic::{AtomicBool, Ordering};

use relm4::gtk::gdk::{Key, ModifierType};

use rust_commander::ops::Choice;

pub static SYNCING: AtomicBool = AtomicBool::new(false);

pub fn syncing() -> bool {
    SYNCING.load(Ordering::Relaxed)
}

